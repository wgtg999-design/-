// Reproducible delivery variants; original supplied files are never modified.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),require=createRequire(import.meta.url);
const sharp=require(require.resolve('sharp',{paths:[path.dirname(require.resolve('next/package.json'))]}));
const folder=path.join(root,'public/assets'),files=(await fs.readdir(folder)).filter(name=>name.endsWith('.png')),variants={};
let originalBytes=0,deliveryBytes=0;
for(const file of files){
 const original=await fs.readFile(path.join(folder,file)),hash=createHash('sha256').update(original).digest('hex').slice(0,12),meta=await sharp(original).metadata(),items=[];originalBytes+=original.length;
 for(const target of [480,960,1600,meta.width]){
  const width=Math.min(target,meta.width);if(items.some(item=>item.width===width))continue;
  const name=file.slice(0,-4)+'-'+hash+'-'+width+'.webp',output=path.join(folder,name);
  try{await fs.access(output)}catch{await sharp(original).resize({width,withoutEnlargement:true}).webp({quality:88,effort:5}).toFile(output)}
  items.push({width,url:'/assets/'+name,bytes:(await fs.stat(output)).size});
 }
 variants['/assets/'+file]={width:meta.width,height:meta.height,items};deliveryBytes+=(items.find(item=>item.width>=960)||items.at(-1)).bytes;
}
const json=JSON.stringify(variants);
await fs.writeFile(path.join(root,'lib/image-variants.ts'),'// Generated by scripts/optimize-images.mjs from unmodified originals.\nexport const imageVariants='+json+' as const;\n');
await fs.writeFile(path.join(root,'public/image-variants.js'),`(()=>{const variants=${json};const entry=value=>variants[value];const src=(value,width=960)=>{const items=entry(value)?.items;return items?(items.find(item=>item.width>=width)||items.at(-1)).url:value};const srcset=value=>entry(value)?.items.map(item=>item.url+' '+item.width+'w').join(', ')||'';window.StoreImages=Object.freeze({variants,src,srcset});})();\n`);
console.log(JSON.stringify({images:files.length,originalBytes,delivery960Bytes:deliveryBytes,reductionPercent:Math.round((1-deliveryBytes/originalBytes)*100)}));
